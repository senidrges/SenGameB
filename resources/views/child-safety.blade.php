            <h1>Normes de sécurité des enfants de LoveGames</h1>
            <p class="updated">Application LoveGames, éditée par Seninova Group</p>

            <p>
                LoveGames interdit strictement toute forme d'exploitation et d'abus sexuels sur mineurs (ESEA),
                y compris les contenus d'abus sexuels sur mineurs (CSAM). Cette page décrit nos règles et la façon
                dont nous les faisons respecter.
            </p>

            <h2>Réservée aux adultes</h2>
            <p>
                LoveGames est réservée aux personnes âgées de <strong>18 ans ou plus</strong>. Tout compte dont nous
                apprenons qu'il appartient à un mineur est suspendu.
            </p>

            <h2>Ce qui est interdit</h2>
            <ul>
                <li>Publier, envoyer, partager ou demander des images, vidéos, fichiers ou textes à caractère sexuel impliquant un mineur.</li>
                <li>Entrer en contact avec un mineur dans un but sexuel (pédopiégeage ou « grooming »), y compris par la séduction, le chantage ou la manipulation.</li>
                <li>Sexualiser un mineur de quelque manière que ce soit, y compris par des contenus dessinés, générés ou modifiés.</li>
                <li>Faciliter, promouvoir ou organiser la traite ou l'exploitation de mineurs.</li>
            </ul>

            <h2>Signaler un problème dans l'application</h2>
            <p>Chaque utilisateur peut signaler, à tout moment et sans quitter l'application :</p>
            <ul>
                <li>un compte, depuis la conversation avec cette personne ;</li>
                <li>un message, en appuyant longuement dessus ;</li>
                <li>un jeu ou un message de jeu.</li>
            </ul>
            <p>
                Les motifs <strong>« Utilisateur mineur »</strong> et <strong>« Contenu sexuel ou inapproprié »</strong>
                sont proposés. Une copie du contenu signalé est conservée pour les modérateurs, même si son auteur le
                supprime ensuite. L'utilisateur peut aussi bloquer la personne concernée.
            </p>

            <h2>Ce que nous faisons</h2>
            <ul>
                <li>Les signalements liés à la sécurité des enfants sont examinés en priorité par notre équipe de modération.</li>
                <li>Le contenu en cause est supprimé pour tous les participants.</li>
                <li>Le compte de son auteur est suspendu : il ne peut plus se connecter ni utiliser l'application.</li>
                <li>
                    Tout contenu d'abus sexuels sur mineurs avéré est signalé aux autorités régionales et nationales
                    compétentes, et nous coopérons avec elles conformément à la loi.
                </li>
            </ul>

